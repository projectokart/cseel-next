/**
 * Helper to create a Google Material Icon React component for any icon name.
 */
function createGoogleMaterialIcon(iconName: string): LucideIcon {
  const pathData =
    GOOGLE_MATERIAL_SVG_PATHS[iconName] ||
    GOOGLE_MATERIAL_SVG_PATHS.HelpCircle ||
    '';

  const Component = React.forwardRef<SVGSVGElement, LucideProps>(
    ({ size = 20, color = 'currentColor', className = '', style, children, strokeWidth, absoluteStrokeWidth, ...rest }, ref) => {
      const isLoader = iconName === 'Loader2';
      return (
        <svg
          ref={ref}
          xmlns="http://www.w3.org/2000/svg"
          viewBox="0 0 24 24"
          width={size}
          height={size}
          fill={color}
          stroke="none"
          data-google-icon={iconName}
          className={`${isLoader ? 'animate-spin ' : ''}${className}`}
          style={{ display: 'inline-block', verticalAlign: 'middle', flexShrink: 0, ...style }}
          {...rest}
        >
          <path d={pathData} />
          {children}
        </svg>
      );
    }
  );
  Component.displayName = `GoogleMaterial_${iconName}`;
  return Component;
}

